use std::{fmt::Write, path::Path};

use crate::metadata::SessionMetadata;

pub const MARKER_START: &str = "<!-- sepia:pr-demo:start -->";
pub const MARKER_END: &str = "<!-- sepia:pr-demo:end -->";

/// Renders a local video reference for native `gh pr edit --attach` to rewrite.
/// The caller supplies the same absolute path to gh; the file need not exist yet.
#[must_use]
pub fn render_pr_block(metadata: &SessionMetadata, video: &Path) -> String {
    let mut md = String::new();
    md.push_str(MARKER_START);
    md.push_str("\n## Sepia Demo\n\n");

    if let Some(description) = &metadata.description {
        md.push_str("> ");
        md.push_str(description);
        md.push_str("\n\n");
    }

    md.push_str("### Recording\n\n![](");
    push_markdown_path(&mut md, video);
    md.push_str(")\n\n");
    write!(
        md,
        "**Duration:** {:.1}s · **Frames:** {} · **FPS:** {}\n\n",
        metadata.duration_seconds(),
        metadata.frame_count,
        metadata.output_fps
    )
    .expect("writing to a String cannot fail");

    let session_name = metadata
        .video
        .parent()
        .and_then(Path::file_name)
        .and_then(|name| name.to_str())
        .unwrap_or("session");
    md.push_str("---\n<sub>Session: `");
    md.push_str(session_name);
    md.push_str("` · Generated by Sepia</sub>\n");
    md.push_str(MARKER_END);
    md.push('\n');
    md
}

fn push_markdown_path(md: &mut String, path: &Path) {
    // gh matches literal destinations and then URL-path-decodes them. Encode
    // Markdown punctuation and '%' too, so filenames cannot change the syntax.
    const HEX: &[u8; 16] = b"0123456789ABCDEF";
    for &byte in path.as_os_str().as_encoded_bytes() {
        if byte.is_ascii_alphanumeric() || b"/-._~".contains(&byte) {
            md.push(char::from(byte));
        } else {
            md.push('%');
            md.push(char::from(HEX[usize::from(byte >> 4)]));
            md.push(char::from(HEX[usize::from(byte & 0x0f)]));
        }
    }
}

#[must_use]
pub fn upsert_marked_block_at_top(existing_body: &str, sepia_block: &str) -> String {
    let body_without_existing = remove_marked_block(existing_body);
    let mut updated = sepia_block.trim().to_string();
    let rest = body_without_existing.trim();
    if !rest.is_empty() {
        updated.push_str("\n\n");
        updated.push_str(rest);
    }
    updated.push('\n');
    updated
}

fn remove_marked_block(existing_body: &str) -> String {
    let Some(start) = existing_body.find(MARKER_START) else {
        return existing_body.to_string();
    };
    let Some(relative_end) = existing_body[start..].find(MARKER_END) else {
        return existing_body.to_string();
    };
    let end = start + relative_end + MARKER_END.len();
    let mut body = String::new();
    body.push_str(existing_body[..start].trim_end());
    let suffix = existing_body[end..].trim_start();
    if !body.is_empty() && !suffix.is_empty() {
        body.push_str("\n\n");
    }
    body.push_str(suffix);
    body
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escapes_local_attachment_paths_without_losing_filename_bytes() {
        let mut destination = String::new();
        push_markdown_path(
            &mut destination,
            Path::new("/tmp/space (take #1)/démo%20.mp4"),
        );
        assert_eq!(
            destination,
            "/tmp/space%20%28take%20%231%29/d%C3%A9mo%2520.mp4"
        );
    }

    #[test]
    fn places_marked_block_at_top_and_preserves_surrounding_text() {
        let existing =
            "Intro\n\n<!-- sepia:pr-demo:start -->\nold\n<!-- sepia:pr-demo:end -->\n\nTail";
        let replacement = "<!-- sepia:pr-demo:start -->\nnew\n<!-- sepia:pr-demo:end -->";
        let updated = upsert_marked_block_at_top(existing, replacement);
        assert_eq!(updated, format!("{replacement}\n\nIntro\n\nTail\n"));
    }

    #[test]
    fn prepends_marked_block_when_missing() {
        let replacement = "<!-- sepia:pr-demo:start -->\nnew\n<!-- sepia:pr-demo:end -->";
        assert_eq!(
            upsert_marked_block_at_top("Intro", replacement),
            format!("{replacement}\n\nIntro\n")
        );
    }

    #[test]
    fn preserves_text_after_an_unclosed_marker() {
        let existing = "Intro\n\n<!-- sepia:pr-demo:start -->\nKeep this text";
        let replacement = "<!-- sepia:pr-demo:start -->\nnew\n<!-- sepia:pr-demo:end -->";
        assert_eq!(
            upsert_marked_block_at_top(existing, replacement),
            format!("{replacement}\n\n{existing}\n")
        );
    }
}
